def generate_description(category: str) -> str:
    """Всегда store + item — двойной сигнал для классификации."""
    tmpl = TEMPLATES[category]
    store = random.choice(tmpl["stores"])
    item = random.choice(tmpl["items"])
    return f"{store} {item}"


def generate_amount(category: str) -> float:
    lo, hi = AMOUNT_RANGES.get(category, (-5000, -100))
    return round(random.uniform(lo, hi), 2)


def main():
    data_path = Path(__file__).parent / "transactions_dataset.csv"
    existing = pd.read_csv(data_path)
    existing["description"] = existing["description"].str.strip()
    print(f"Существующий датасет: {len(existing)} строк, {existing['category'].nunique()} категорий")

    target_per_category = 200
    new_rows = []

    for category in TEMPLATES.keys():
        existing_descs = set(existing[existing["category"] == category]["description"].tolist())
        count = len(existing_descs)
        need = max(0, target_per_category - count)

        added = 0
        attempts = 0
        while added < need and attempts < need * 20:
            desc = generate_description(category)
            attempts += 1
            if desc not in existing_descs:
                existing_descs.add(desc)
                new_rows.append({
                    "description": desc,
                    "amount": generate_amount(category),
                    "category": category,
                })
                added += 1

    new_df = pd.DataFrame(new_rows)
    combined = pd.concat([existing, new_df], ignore_index=True)
    combined = combined.drop_duplicates(subset=["description", "category"])
    combined = combined.sample(frac=1, random_state=42).reset_index(drop=True)

    combined.to_csv(data_path, index=False)
    print(f"Итоговый датасет: {len(combined)} строк, {combined['category'].nunique()} категорий")
    print(combined["category"].value_counts().to_string())


if __name__ == "__main__":
    main()
