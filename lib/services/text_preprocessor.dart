/// Простой текстовый препроцессор для офлайн ML.
/// Без лемматизации (pymorphy2 — Python-only), но char n-grams компенсируют.
class TextPreprocessor {
  static const Set<String> _stopWords = {
    // Русские стоп-слова
    'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со', 'как',
    'а', 'то', 'все', 'она', 'так', 'его', 'но', 'да', 'ты', 'к', 'у',
    'же', 'вы', 'за', 'бы', 'по', 'только', 'ее', 'мне', 'было', 'вот',
    'от', 'меня', 'еще', 'нет', 'о', 'из', 'ему', 'теперь', 'когда',
    'даже', 'ну', 'вдруг', 'ли', 'если', 'уже', 'или', 'ни', 'быть',
    'был', 'него', 'до', 'вас', 'нибудь', 'опять', 'уж', 'вам', 'ведь',
    'там', 'потом', 'себя', 'ничего', 'ей', 'может', 'они', 'тут', 'где',
    'есть', 'надо', 'ней', 'для', 'мы', 'тебя', 'их', 'чем', 'была',
    'сам', 'чтоб', 'без', 'будто', 'чего', 'раз', 'тоже', 'себе', 'под',
    'будет', 'ж', 'тогда', 'кто', 'этот', 'того', 'потому', 'этого',
    'какой', 'совсем', 'ним', 'здесь', 'этом', 'один', 'почти', 'мой',
    'тем', 'чтобы', 'нее', 'сейчас', 'были', 'куда', 'зачем', 'всех',
    'никогда', 'можно', 'при', 'наконец', 'два', 'об', 'другой', 'хоть',
    'после', 'над', 'больше', 'тот', 'через', 'эти', 'нас', 'про',
    'между', 'такой', 'сих', 'три', 'эту', 'моя', 'впрочем', 'хорошо',
    'свою', 'этой', 'перед', 'иногда', 'лучше', 'чуть', 'том', 'нельзя',
    'такого', 'всем', 'всего',
    // Английские стоп-слова
    'the', 'a', 'an', 'is', 'in', 'on', 'at', 'to', 'for', 'of', 'and',
    'or', 'but', 'not', 'with', 'from', 'by', 'was', 'are', 'be', 'it',
    'as', 'that', 'this', 'we', 'you', 'he', 'she', 'they',
  };

  /// Токенизация и очистка текста (без лемматизации).
  /// Аналогично Python-серверу: только буквы/цифры, нижний регистр, без стоп-слов.
  static List<String> tokenize(String text) {
    final lower = text.toLowerCase();
    // Разбиваем на токены (только буквы и цифры)
    final tokens = RegExp(r'[a-zA-Zа-яёА-ЯЁ0-9]+')
        .allMatches(lower)
        .map((m) => m.group(0)!)
        .where((t) => t.length > 1 && !_stopWords.contains(t))
        .toList();
    return tokens;
  }

  /// Собираем word n-grams из токенов.
  static List<String> wordNgrams(List<String> tokens, int n) {
    if (tokens.length < n) return tokens.isEmpty ? [] : [];
    final result = <String>[];
    for (int i = 0; i <= tokens.length - n; i++) {
      result.add(tokens.sublist(i, i + n).join(' '));
    }
    return result;
  }

  /// Собираем char n-grams из строки (char_wb аналог — добавляем пробелы по краям).
  static List<String> charNgrams(String text, int minN, int maxN) {
    final padded = ' $text ';
    final result = <String>[];
    for (int n = minN; n <= maxN; n++) {
      for (int i = 0; i <= padded.length - n; i++) {
        result.add(padded.substring(i, i + n));
      }
    }
    return result;
  }
}
